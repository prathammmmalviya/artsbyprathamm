-- Run this in Supabase Dashboard -> SQL Editor.
-- Replace c834570d-8b41-4a18-8391-3af9bd57c194 with the auth.users.id of the admin account you create.

create table if not exists public.artworks (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  category text not null check (category in ('portrait','devotional','studies')),
  medium text not null default '',
  size text not null default '',
  price numeric(10,2),
  availability text not null default 'Available',
  description text not null default '',
  image_url text not null
);

alter table public.artworks enable row level security;

drop policy if exists "Anyone can view artworks" on public.artworks;
create policy "Anyone can view artworks"
on public.artworks for select using (true);

drop policy if exists "Admin can add artworks" on public.artworks;
create policy "Admin can add artworks"
on public.artworks for insert
to authenticated
with check (auth.uid() = 'c834570d-8b41-4a18-8391-3af9bd57c194'::uuid and owner_id = auth.uid());

drop policy if exists "Admin can update artworks" on public.artworks;
create policy "Admin can update artworks"
on public.artworks for update
to authenticated
using (auth.uid() = 'c834570d-8b41-4a18-8391-3af9bd57c194'::uuid)
with check (auth.uid() = 'c834570d-8b41-4a18-8391-3af9bd57c194'::uuid and owner_id = auth.uid());

drop policy if exists "Admin can delete artworks" on public.artworks;
create policy "Admin can delete artworks"
on public.artworks for delete
to authenticated
using (auth.uid() = 'c834570d-8b41-4a18-8391-3af9bd57c194'::uuid);

-- Public image bucket for portfolio photos.
